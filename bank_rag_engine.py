def md_to_html(text: str) -> str:
    if not text:
        return ""
    cleaned_text = strip_diacritics(text)
    lines = cleaned_text.splitlines()
    out, in_ul = [], False

    for raw_line in lines:
        s = raw_line.strip()
        if not s:
            if in_ul:
                out.append("</ul>")
                in_ul = False
            continue

        # معالجة العناوين (### أو ##)
        if s.startswith("### ") or s.startswith("## "):
            if in_ul:
                out.append("</ul>")
                in_ul = False
            heading_txt = html.escape(re.sub(r"^#+\s*", "", s)).replace("**", "")
            out.append(
                f"<h4 style='color:{CBE_NAVY};font-size:15.5px;font-weight:800;"
                f"margin-top:14px;margin-bottom:6px;border-bottom:1px solid #E2E8F0;padding-bottom:4px;'>"
                f"{heading_txt}</h4>"
            )
            continue

        escaped = html.escape(s)
        escaped = re.sub(r"\*\*(.+?)\*\*", rf"<b style='color:{CBE_NAVY};'>\1</b>", escaped)
        escaped = re.sub(
            r"(https?://[^\s<]+)",
            r'<a href="\1" target="_blank" style="color:#92400E;text-decoration:underline;">\1</a>',
            escaped
        )

        # معالجة القوائم النقطية والرقمية مع مسافة بادئة صحيحة RTL
        is_bullet = escaped.startswith("- ") or escaped.startswith("* ") or escaped.startswith("• ")
        is_numbered = bool(re.match(r"^\d+[\.\-\)]\s+", escaped))

        if is_bullet or is_numbered:
            if not in_ul:
                out.append("<ul style='padding-right:22px;margin-right:4px;margin-bottom:10px;list-style-type:disc;'>")
                in_ul = True
            item_body = re.sub(r"^([-*•]|\d+[\.\-\)])\s+", "", escaped)
            out.append(f"<li style='margin-bottom:6px;line-height:1.85;'>{item_body}</li>")
        else:
            if in_ul:
                out.append("</ul>")
                in_ul = False
            out.append(f"<p style='margin-bottom:8px;line-height:1.85;'>{escaped}</p>")

    if in_ul:
        out.append("</ul>")
    return "\n".join(out)

