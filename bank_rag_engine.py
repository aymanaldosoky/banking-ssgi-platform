def _post_json(url, payload, headers, timeout=45):
    req = urllib.request.Request(url, data=json.dumps(payload).encode("utf-8"), headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read().decode("utf-8"))

def llm_available():
    return bool(os.getenv("ANTHROPIC_API_KEY") or os.getenv("GEMINI_API_KEY"))

def call_llm(prompt):
    try:
        if os.getenv("ANTHROPIC_API_KEY"):
            out = _post_json(
                "https://api.anthropic.com/v1/messages",
                {"model": os.getenv("BANK_RAG_ANTHROPIC_MODEL", "claude-sonnet-5-5"),
                 "max_tokens": 1500, "messages": [{"role": "user", "content": prompt}]},
                {"content-type": "application/json", "x-api-key": os.environ["ANTHROPIC_API_KEY"],
                 "anthropic-version": "2023-06-01"})
            return "".join(b.get("text", "") for b in out.get("content", []))
        if os.getenv("GEMINI_API_KEY"):
            model = os.getenv("GEMINI_MODEL", "gemini-2.5-flash")
            out = _post_json(
                f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent",
                {"contents": [{"parts": [{"text": prompt}]}]},
                {"content-type": "application/json", "x-goog-api-key": os.environ["GEMINI_API_KEY"]})
            return out["candidates"][0]["content"]["parts"][0]["text"]
    except Exception as e:
        print(f"LLM Call Error: {e}")
        return None
    return None

