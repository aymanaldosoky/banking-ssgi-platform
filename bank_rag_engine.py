def classify_intent(question: str):
    q = norm(question)
    best, best_score = None, 0
    for intent, kws in INTENT_KEYWORDS.items():
        score = sum(len(norm(k)) for k in kws if norm(k) in q)
        if score > best_score:
            best, best_score = intent, score
    return best


