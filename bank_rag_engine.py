def process_rag_gemini_query(bank_name, question):
    if bank_name == "اختر البنك المصرفي" or not (question or "").strip():
        return "⚠️ يرجى اختيار البنك المصرفي وكتابة السؤال أو الاستفسار التنظيمي بدقة للحصول على التحليل."
    if not is_valid_arabic_question(question):
        return "⚠️ **تنبيه:** يرجى كتابة سؤال واضح باللغة العربية لكي تتمكن المنصة من تحليله."

    p = profile_of(bank_name)
    intents = classify_intents(question)
    primary = intents[0] if intents else None

    # الطبقة 1: الأرشيف
    arch = archive_lookup(bank_name, question, primary)
    if arch:
        if os.getenv("BANK_RAG_ENRICH") == "1" and llm_available():
            txt = call_llm(build_prompt(bank_name, question, p, archive_text=arch))
            if txt:
                return render_card(bank_name, question, md_to_html(txt), "llm")
        return render_card(bank_name, question, arch, "archive")

    # الطبقة 2: الملف التنفيذي
    parts = []
    for it in intents:
        r = _compose(it, bank_name, p, question)
        if r:
            parts.append(r)
    if parts:
        if len(parts) == 1:
            _, body, tier = parts[0]
        else:
            body = _SEP.join(h.replace(FOOT_HTML, "") for _, h, _ in parts)
            if FOOT_HTML in "".join(h for _, h, _ in parts):
                body += FOOT_HTML
            tier = "llm" if all(t == "llm" for _, _, t in parts) else "profile"
        return render_card(bank_name, question, body, tier)

    # الطبقة 3: LLM
    if llm_available():
        txt = call_llm(build_prompt(bank_name, question, p))
        if txt:
            return render_card(bank_name, question, md_to_html(txt), "llm")

    # الطبقة 4: الفجوة
    gap = f"<p>لا تتوفر لدى المنصة بيانات موثقة تكفي للإجابة عن هذا السؤال بخصوص <b>{html.escape(bank_name)}</b>.</p>"
    return render_card(bank_name, question, gap, "gap")

