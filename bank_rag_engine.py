    for key, text in d.items():
        k = norm(key)
        if k in q:
            return text
        kw = {w for w in k.split() if len(w) > 3}
        if not kw:
            continue
        score = len(kw & qwords) / len(kw)
        if score > best_score:
            best, best_score = text, score
    return best if best_score >= 0.6 else None


